namespace Jeninnet.Validation.ClientRules;

/// <summary>
/// Writes deterministic client-side rule payloads (JSON, TypeScript, and
/// JavaScript) from validator descriptors.
/// </summary>
public static class ClientRulesWriter {
    /// <summary>
    /// Writes a client-rules document from validator descriptors.
    /// </summary>
    /// <param name="descriptors">The validator descriptors.</param>
    /// <param name="options">Optional export options.</param>
    /// <returns>The document as a JSON object.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="descriptors"/> is null.</exception>
    /// <exception cref="ArgumentException">A descriptor is null or <see cref="ClientRulesOptions.SchemaVersion"/> is empty.</exception>
    public static JsonObject Write(
        IEnumerable<IValidationDescriptor> descriptors,
        ClientRulesOptions? options = null) {
        ArgumentNullException.ThrowIfNull(descriptors);

        options ??= new ClientRulesOptions();
        ArgumentException.ThrowIfNullOrWhiteSpace(options.SchemaVersion);

        var exported = new Dictionary<string, IValidationDescriptor>(StringComparer.Ordinal);

        foreach(var descriptor in descriptors) {
            if(descriptor is null) {
                throw new ArgumentException("The descriptor sequence contains a null entry.", nameof(descriptors));
            }

            if(options.IncludedValidators.Count > 0 &&
               !options.IncludedValidators.Contains(descriptor.ValidatorName)) {
                continue;
            }

            exported[descriptor.ValidatorName] = descriptor;
        }

        var root = new JsonObject {
            ["schemaVersion"] = options.SchemaVersion
        };

        var validators = new JsonArray();

        foreach(var descriptor in exported.Values.OrderBy(
                    static descriptor => descriptor.ValidatorName, StringComparer.Ordinal)) {
            validators.Add((JsonNode)WriteValidator(descriptor, options));
        }

        root["validators"] = validators;
        return root;
    }

    /// <summary>
    /// Writes a client-rules document from validator descriptor providers.
    /// </summary>
    /// <param name="providers">The descriptor providers.</param>
    /// <param name="options">Optional export options.</param>
    /// <returns>The document as a JSON object.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="providers"/> is null.</exception>
    public static JsonObject Write(
        IEnumerable<IValidationDescriptorProvider> providers,
        ClientRulesOptions? options = null) {
        ArgumentNullException.ThrowIfNull(providers);

        return Write(providers.Select(static provider => {
            ArgumentNullException.ThrowIfNull(provider);
            return provider.Describe();
        }), options);
    }

    /// <summary>
    /// Writes a client-rules document as indented JSON.
    /// </summary>
    /// <param name="descriptors">The validator descriptors.</param>
    /// <param name="options">Optional export options.</param>
    /// <returns>The indented JSON document.</returns>
    public static string WriteToString(
        IEnumerable<IValidationDescriptor> descriptors,
        ClientRulesOptions? options = null) =>
        Write(descriptors, options).ToJsonString(new JsonSerializerOptions { WriteIndented = true });

    /// <summary>
    /// Writes a client-rules document as indented JSON.
    /// </summary>
    /// <param name="providers">The descriptor providers.</param>
    /// <param name="options">Optional export options.</param>
    /// <returns>The indented JSON document.</returns>
    public static string WriteToString(
        IEnumerable<IValidationDescriptorProvider> providers,
        ClientRulesOptions? options = null) =>
        Write(providers, options).ToJsonString(new JsonSerializerOptions { WriteIndented = true });

    /// <summary>
    /// Writes an ES module with TypeScript declarations and the rule payload.
    /// </summary>
    /// <param name="descriptors">The validator descriptors.</param>
    /// <param name="options">Optional export options.</param>
    /// <returns>The TypeScript module source.</returns>
    public static string WriteTypeScript(
        IEnumerable<IValidationDescriptor> descriptors,
        ClientRulesOptions? options = null) {
        var json = WriteToString(descriptors, options);

        return $$"""
            // <auto-generated/>
            // Client-side validation rules generated from Jeninnet.Validation descriptors.
            // The server remains authoritative; use this data for early feedback only.

            export type ClientRuleSeverity = "Error" | "Warning" | "Info";

            export interface ClientRule {
                readonly rule: string;
                readonly messageKey: string | null;
                readonly message?: string;
                readonly severity: ClientRuleSeverity;
                readonly hasCondition: boolean;
                readonly serverOnly?: boolean;
                readonly params: Readonly<Record<string, string | number | boolean | null>>;
            }

            export interface ClientMember {
                readonly name: string;
                readonly rules: readonly ClientRule[];
            }

            export interface ClientValidator {
                readonly name: string;
                readonly type: string | null;
                readonly members: readonly ClientMember[];
            }

            export interface ClientRulesDocument {
                readonly schemaVersion: string;
                readonly validators: readonly ClientValidator[];
            }

            export const clientRules: ClientRulesDocument = {{json}} as const;
            """;
    }

    /// <summary>
    /// Writes an ES module with the rule payload.
    /// </summary>
    /// <param name="descriptors">The validator descriptors.</param>
    /// <param name="options">Optional export options.</param>
    /// <returns>The JavaScript module source.</returns>
    public static string WriteJavaScript(
        IEnumerable<IValidationDescriptor> descriptors,
        ClientRulesOptions? options = null) {
        var json = WriteToString(descriptors, options);

        return $$"""
            // <auto-generated/>
            // Client-side validation rules generated from Jeninnet.Validation descriptors.
            // The server remains authoritative; use this data for early feedback only.

            export const clientRules = {{json}};
            """;
    }

    private static JsonObject WriteValidator(IValidationDescriptor descriptor, ClientRulesOptions options) {
        var validator = new JsonObject {
            ["name"] = descriptor.ValidatorName
        };

        if(descriptor.ValidatedType is { } validatedType) {
            validator["type"] = validatedType.FullName ?? validatedType.Name;
        }

        var members = new JsonArray();

        foreach(var member in descriptor.Members
                    .Where(static member => member.Rules.Count > 0)
                    .OrderBy(static member => member.Name, StringComparer.Ordinal)) {
            var memberNode = new JsonObject {
                ["name"] = member.Name
            };

            var rules = new JsonArray();

            foreach(var rule in member.Rules) {
                rules.Add((JsonNode)WriteRule(rule, options));
            }

            memberNode["rules"] = rules;
            members.Add((JsonNode)memberNode);
        }

        validator["members"] = members;
        return validator;
    }

    private static JsonObject WriteRule(IValidationRuleDescriptor rule, ClientRulesOptions options) {
        var node = new JsonObject {
            ["rule"] = rule.Kind,
            ["messageKey"] = rule.MessageKey,
            ["severity"] = rule.Severity.ToString(),
            ["hasCondition"] = rule.HasCondition
        };

        if(ClientRuleSupport.IsServerOnly(rule)) {
            node["serverOnly"] = true;
        }

        if(rule.MessageIsAuthored) {
            node["messageIsAuthored"] = true;
        }

        if(rule.ErrorCode is not null) {
            node["errorCode"] = rule.ErrorCode;
        }

        if(rule.DisplayName is not null) {
            node["displayName"] = rule.DisplayName;
        }

        if(rule.CustomState is not null) {
            node["customState"] = JsonValueFactory.ToNode(rule.CustomState);
        }

        var message = options.MessageResolver?.Invoke(rule);
        if(message is not null) {
            node["message"] = message;
        }

        var parameters = new JsonObject();

        foreach(var parameter in rule.Parameters.OrderBy(static parameter => parameter.Key, StringComparer.Ordinal)) {
            parameters[parameter.Key] = JsonValueFactory.ToNode(parameter.Value);
        }

        node["params"] = parameters;
        return node;
    }
}
