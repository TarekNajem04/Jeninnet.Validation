namespace Jeninnet.Validation.Generators.Emitter;

/// <summary>
/// Emits the optional <c>ClientRulesCatalog</c> source file that carries the
/// deterministic client-rules JSON for all generated validators.
/// </summary>
internal static class ClientRulesCatalogEmitter {
    internal const string SCHEMA_VERSION = "1.0";
    internal const string CATALOG_NAMESPACE = "Jeninnet.Validation.Generated";
    internal const string CATALOG_CLASS = "ClientRulesCatalog";

    /// <summary>
    /// Emits the catalog source for the supplied descriptors.
    /// </summary>
    /// <param name="descriptors">The generated validator descriptors.</param>
    /// <returns>The generated C# source.</returns>
    internal static string Emit(IReadOnlyList<ValidatorDescriptor> descriptors) {
        var json = BuildJson(descriptors);
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>")
            .AppendLine($"// This file was generated by {ValidatorEmitter.GENERATOR_FULL_NAME} v{ValidatorEmitter.GENERATOR_VERSION}.")
            .AppendLine("// Do not edit this file manually — changes will be overwritten on next build.")
            .AppendLine("#nullable enable")
            .AppendLine()
            .AppendLine($"namespace {CATALOG_NAMESPACE};")
            .AppendLine()
            .AppendLine("/// <summary>")
            .AppendLine("/// Build-time client-side validation rules for all generated validators.")
            .AppendLine("/// </summary>")
            .AppendLine($"[System.CodeDom.Compiler.GeneratedCode(\"{ValidatorEmitter.GENERATOR_FULL_NAME}\", \"{ValidatorEmitter.GENERATOR_VERSION}\")]")
            .AppendLine($"public static class {CATALOG_CLASS} {{")
            .AppendLine("    /// <summary>")
            .AppendLine("    /// The client-rules payload schema version.")
            .AppendLine("    /// </summary>")
            .AppendLine($"    public const string SchemaVersion = \"{SCHEMA_VERSION}\";")
            .AppendLine()
            .AppendLine("    /// <summary>")
            .AppendLine("    /// The deterministic client-rules JSON for all generated validators.")
            .AppendLine("    /// </summary>")
            .AppendLine($"    public const string Json = \"{ToCSharpLiteral(json)}\";")
            .AppendLine("}");

        return sb.ToString();
    }

    private static string BuildJson(IReadOnlyList<ValidatorDescriptor> descriptors) {
        var sb = new StringBuilder();
        sb.Append("{\"schemaVersion\":\"").Append(SCHEMA_VERSION).Append("\",\"validators\":[");

        var ordered = descriptors
            .OrderBy(static descriptor => GetValidatorFullName(descriptor), StringComparer.Ordinal)
            .ToList();

        for(var i = 0; i < ordered.Count; i++) {
            if(i > 0) {
                sb.Append(',');
            }

            AppendValidator(sb, ordered[i]);
        }

        sb.Append("]}");
        return sb.ToString();
    }

    private static void AppendValidator(StringBuilder sb, ValidatorDescriptor descriptor) {
        var typeName = descriptor.TargetTypeName.Replace(NamingUtilities.GLOBAL_PREFIX, "");

        sb.Append("{\"name\":\"").Append(EscapeJson(GetValidatorFullName(descriptor))).Append('"')
            .Append(",\"type\":\"").Append(EscapeJson(typeName)).Append('"')
            .Append(",\"members\":[");

        var members = descriptor.Properties
            .Where(static property => property.Rules.Count > 0)
            .OrderBy(static property => property.Name, StringComparer.Ordinal)
            .ToList();

        for(var i = 0; i < members.Count; i++) {
            if(i > 0) {
                sb.Append(',');
            }

            AppendMember(sb, members[i]);
        }

        sb.Append("]}");
    }

    private static void AppendMember(StringBuilder sb, ValidatorPropertyDescriptor member) {
        sb.Append("{\"name\":\"").Append(EscapeJson(member.Name)).Append('"')
            .Append(",\"rules\":[");

        for(var i = 0; i < member.Rules.Count; i++) {
            if(i > 0) {
                sb.Append(',');
            }

            AppendRule(sb, member.Rules[i]);
        }

        sb.Append("]}");
    }

    private static void AppendRule(StringBuilder sb, ValidationRuleDescriptor rule) {
        var hasCondition = HasCondition(rule);

        AppendRuleHeader(sb, rule, hasCondition);
        AppendRuleMetadata(sb, rule, hasCondition);
        AppendRuleParameters(sb, rule);
    }

    private static bool HasCondition(ValidationRuleDescriptor rule) =>
        rule.Options.WhenAsyncCondition is not null ||
        rule.Options.UnlessAsyncCondition is not null ||
        rule.Options.WhenCondition is not null ||
        rule.Options.UnlessCondition is not null;

    private static void AppendRuleHeader(StringBuilder sb, ValidationRuleDescriptor rule, bool hasCondition) {
        var kind = GetCatalogRuleKind(rule.Kind);

        sb.Append("{\"rule\":\"").Append(EscapeJson(kind)).Append('"')
            .Append(",\"messageKey\":");
        AppendMessageKey(sb, ValidatorEmitter.GetDescriptorMessageKey(rule.Kind));
        sb.Append(",\"severity\":\"").Append(EscapeJson(rule.Options.Severity ?? "Error")).Append('"')
            .Append(",\"hasCondition\":").Append(hasCondition ? "true" : "false");
    }

    private static string GetCatalogRuleKind(RuleKind kind) =>
        kind switch {
            RuleKind.StringNotEmpty => "NotEmpty",
            RuleKind.MaximumLength or RuleKind.MinimumLength => "Length",
            _ => kind.ToString()
        };

    private static void AppendMessageKey(StringBuilder sb, string? messageKey) {
        if(messageKey is null) {
            sb.Append("null");
            return;
        }

        sb.Append('"').Append(EscapeJson(messageKey)).Append('"');
    }

    private static void AppendRuleMetadata(StringBuilder sb, ValidationRuleDescriptor rule, bool hasCondition) {
        if(rule.Options.Message is not null) {
            sb.Append(",\"messageIsAuthored\":true");
        }

        if(hasCondition || !IsClientSupported(rule.Kind)) {
            sb.Append(",\"serverOnly\":true");
        }

        if(rule.Options.ErrorCode is not null) {
            sb.Append(",\"errorCode\":\"").Append(EscapeJson(rule.Options.ErrorCode)).Append('"');
        }

        if(rule.Options.DisplayName is not null) {
            sb.Append(",\"displayName\":\"").Append(EscapeJson(rule.Options.DisplayName)).Append('"');
        }

        if(rule.Options.CustomState is not null) {
            sb.Append(",\"customState\":\"").Append(EscapeJson(rule.Options.CustomState)).Append('"');
        }
    }

    private static void AppendRuleParameters(StringBuilder sb, ValidationRuleDescriptor rule) {
        sb.Append(",\"params\":{");

        var entries = BuildParameterEntries(rule);
        entries.Sort(static (left, right) => string.CompareOrdinal(left.Name, right.Name));

        for(var i = 0; i < entries.Count; i++) {
            if(i > 0) {
                sb.Append(',');
            }

            sb.Append('"').Append(EscapeJson(entries[i].Name)).Append("\":");
            AppendParameterValue(sb, entries[i].Value, entries[i].Parameter?.TypeName);
        }

        sb.Append("}}");
    }

    private static List<(string Name, RuleParameter? Parameter, string? Value)> BuildParameterEntries(
        ValidationRuleDescriptor rule) {
        var entries = new List<(string Name, RuleParameter? Parameter, string? Value)>();

        if(rule.Options.RuleSets is { Count: > 0 }) {
            entries.Add(("RuleSets", null, string.Join(", ", rule.Options.RuleSets)));
        }

        if(rule.Kind is RuleKind.Enum) {
            var enumType = NamingUtilities.GetSimpleName(rule.PropertyTypeName.TrimEnd('?'));
            entries.Add(("EnumType", null, enumType));
        }

        if(rule is ParametricRuleDescriptor parametric) {
            AddParameterEntries(entries, rule.Kind, parametric.Parameters);
        }

        AddDescriptorAliases(entries, rule.Kind);

        return entries;
    }

    private static void AddParameterEntries(
        List<(string Name, RuleParameter? Parameter, string? Value)> entries,
        RuleKind kind,
        IReadOnlyList<RuleParameter> parameters) {
        for(var i = 0; i < parameters.Count; i++) {
            if(kind is RuleKind.In or RuleKind.NotIn or RuleKind.FileExtensions && i > 0) {
                continue;
            }

            var value = kind is RuleKind.FileExtensions && i is 0
                ? NormalizeFileExtensions(parameters[i].Value)
                : parameters[i].Value;

            entries.Add((
                ValidatorEmitter.GetDescriptorParameterName(kind, i),
                parameters[i],
                value));
        }
    }

    private static void AddDescriptorAliases(
        List<(string Name, RuleParameter? Parameter, string? Value)> entries,
        RuleKind kind) {
        switch(kind) {
            case RuleKind.GreaterThan:
            case RuleKind.GreaterThanOrEqual:
            case RuleKind.LessThan:
            case RuleKind.LessThanOrEqual:
            case RuleKind.Equal:
            case RuleKind.NotEqual:
            case RuleKind.After:
            case RuleKind.Before:
                AddAlias(entries, "ComparisonValue", "Threshold");
                break;
            case RuleKind.PropertyEqual:
            case RuleKind.PropertyNotEqual:
            case RuleKind.PropertyGreaterThan:
            case RuleKind.PropertyGreaterThanOrEqual:
            case RuleKind.PropertyLessThan:
            case RuleKind.PropertyLessThanOrEqual:
                AddAlias(entries, "ComparisonProperty", "Other");
                break;
            case RuleKind.InclusiveBetween:
            case RuleKind.ExclusiveBetween:
            case RuleKind.Range:
                AddAlias(entries, "From", "Min");
                AddAlias(entries, "To", "Max");
                break;
            case RuleKind.ExactLength:
                AddAlias(entries, "ExactLength", "Length");
                break;
        }
    }

    private static void AddAlias(
        List<(string Name, RuleParameter? Parameter, string? Value)> entries,
        string alias,
        string source) {
        if(entries.Exists(entry => entry.Name == alias)) {
            return;
        }

        var (Name, Parameter, Value) = entries.Find(entry => entry.Name == source);

        if(Name is not null) {
            entries.Add((alias, Parameter, Value));
        }
    }

    private static string? NormalizeFileExtensions(string? value) {
        if(value is null) {
            return null;
        }

        var extensions = value.Split([','], StringSplitOptions.RemoveEmptyEntries)
                              .Select(static extension => extension.Trim())
                              .Where(static extension => extension.Length > 0)
                              .Select(static extension => extension.StartsWith(".", StringComparison.Ordinal)
                                  ? extension
                                  : "." + extension);

        return string.Join(", ", extensions);
    }

    private static bool IsClientSupported(RuleKind kind) =>
        kind is RuleKind.NotNull or RuleKind.NotEmpty or RuleKind.StringNotEmpty or
            RuleKind.Length or RuleKind.MaximumLength or RuleKind.MinimumLength or RuleKind.ExactLength or
            RuleKind.Regex or RuleKind.Email or RuleKind.Url or RuleKind.IPAddress or
            RuleKind.Phone or RuleKind.CreditCard or RuleKind.Base64String or RuleKind.FileExtensions or
            RuleKind.Contains or RuleKind.StartsWith or RuleKind.EndsWith or
            RuleKind.Count or RuleKind.MinCount or RuleKind.MaxCount or RuleKind.UniqueItems or
            RuleKind.MultipleOf or
            RuleKind.GreaterThan or RuleKind.GreaterThanOrEqual or RuleKind.LessThan or
            RuleKind.LessThanOrEqual or RuleKind.InclusiveBetween or RuleKind.ExclusiveBetween or
            RuleKind.Range or RuleKind.In or RuleKind.NotIn or RuleKind.ScalePrecision or
            RuleKind.After or RuleKind.Before;

    private static void AppendParameterValue(StringBuilder sb, string? value, string? typeName) {
        if(value is null) {
            sb.Append("null");
            return;
        }

        if(TryAppendBoolean(sb, value, typeName) ||
           TryAppendNumber(sb, value, typeName) ||
           TryAppendDateTime(sb, value, typeName)) {
            return;
        }

        sb.Append('"').Append(EscapeJson(value)).Append('"');
    }

    private static bool TryAppendBoolean(StringBuilder sb, string value, string? typeName) {
        if(typeName is not ("bool" or "System.Boolean") || !bool.TryParse(value, out var boolean)) {
            return false;
        }

        sb.Append(boolean ? "true" : "false");
        return true;
    }

    private static bool TryAppendNumber(StringBuilder sb, string value, string? typeName) {
        if(!IsNumericType(typeName)) {
            return false;
        }

        if(long.TryParse(value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var integer)) {
            sb.Append(integer.ToString(CultureInfo.InvariantCulture));
            return true;
        }

        if(decimal.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var number)) {
            sb.Append(number.ToString(CultureInfo.InvariantCulture));
            return true;
        }

        return false;
    }

    private static bool TryAppendDateTime(StringBuilder sb, string value, string? typeName) {
        if(typeName is not ("System.DateTime" or "DateTime") ||
           !DateTime.TryParse(value, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind, out var dateTime)) {
            return false;
        }

        var text = Convert.ToString(dateTime, CultureInfo.InvariantCulture);
        if(text is null) {
            sb.Append("null");
        } else {
            sb.Append('"').Append(EscapeJson(text)).Append('"');
        }

        return true;
    }

    private static bool IsNumericType(string? typeName) =>
        typeName is "byte" or "sbyte" or "short" or "ushort" or "int" or "uint" or
                     "long" or "ulong" or "float" or "double" or "decimal" or
                     "System.Byte" or "System.SByte" or "System.Int16" or "System.UInt16" or
                     "System.Int32" or "System.UInt32" or "System.Int64" or "System.UInt64" or
                     "System.Single" or "System.Double" or "System.Decimal";

    private static string GetValidatorFullName(ValidatorDescriptor descriptor) {
        var typeName = descriptor.TargetTypeName.Replace(NamingUtilities.GLOBAL_PREFIX, "");
        var typeNamespace = NamingUtilities.GetNamespace(typeName);
        var validatorNamespace = string.IsNullOrEmpty(descriptor.TargetNamespace)
            ? $"{typeNamespace}.{ValidatorEmitter.NAMESPACE_SUFFIX}"
            : descriptor.TargetNamespace!;
        var className = NamingUtilities.GetValidatorClassName(typeName);

        return string.IsNullOrEmpty(validatorNamespace)
            ? className
            : $"{validatorNamespace}.{className}";
    }

    private static string EscapeJson(string value) {
        var sb = new StringBuilder(value.Length + 8);

        foreach(var character in value) {
            switch(character) {
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\\':
                    sb.Append("\\\\");
                    break;
                case '\b':
                    sb.Append("\\b");
                    break;
                case '\f':
                    sb.Append("\\f");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                case '\r':
                    sb.Append("\\r");
                    break;
                case '\t':
                    sb.Append("\\t");
                    break;
                default:
                    if(character < ' ') {
                        sb.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                    } else {
                        sb.Append(character);
                    }

                    break;
            }
        }

        return sb.ToString();
    }

    private static string ToCSharpLiteral(string value) =>
        value.Replace("\\", "\\\\")
             .Replace("\"", "\\\"")
             .Replace("\r", "\\r")
             .Replace("\n", "\\n")
             .Replace("\t", "\\t");
}
