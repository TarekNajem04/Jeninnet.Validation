    private static void EmitHookValidateMethods(
        StringBuilder sb,
        string simpleTypeName,
        ValidatorDescriptor descriptor) {
        var preValidateCall = descriptor.PreValidateHasErrors
            ? "_preValidate(instance, context, preErrors)"
            : "_preValidate(instance, context)";
        const string indentation = "        ";
        var contextDeclaration = descriptor.PreValidateExpression is null
            ? string.Empty
            : $"{indentation}var context = new ValidationContext<{simpleTypeName}>(\n" +
              $"{indentation}    instance, string.Empty, ruleSets, FailFast: false, Root: instance);";
        var optionsContextDeclaration = descriptor.PreValidateExpression is null
            ? string.Empty
            : $"{indentation}var context = new ValidationContext<{simpleTypeName}>(\n" +
              $"{indentation}    instance,\n" +
              $"{indentation}    string.Empty,\n" +
              $"{indentation}    options.RuleSets,\n" +
              $"{indentation}    options.FailFast,\n" +
              $"{indentation}    Root: instance,\n" +
              $"{indentation}    ServiceProvider: options.ServiceProvider);";
        var preValidateGuard = descriptor.PreValidateExpression is null
            ? string.Empty
            : $"{indentation}if(_preValidate is not null && !{preValidateCall}) {{\n" +
              $"{indentation}    return Finish(preErrors, ValidationResult.Success);\n" +
              $"{indentation}}}";

        sb.AppendLine(
            $$"""
                /// <summary>
                /// Gets or sets the class-level cascade mode used when a call does not override it.
                /// </summary>
                public CascadeMode ClassLevelCascadeMode {
                    get => _composite.ClassLevelCascadeMode;
                    set => _composite.ClassLevelCascadeMode = value;
                }

                /// <inheritdoc/>
                public ValidationResult Validate({{simpleTypeName}} instance)
                    => Run(instance, (IEnumerable<string>?)null);

                /// <inheritdoc/>
                public ValidationResult Validate({{simpleTypeName}} instance, IEnumerable<string>? ruleSets)
                    => Run(instance, ruleSets);

                /// <inheritdoc/>
                public ValidationResult Validate({{simpleTypeName}} instance, ValidationCallOptions options)
                    => Run(instance, options);

                /// <inheritdoc/>
                public ValidationResult Validate({{simpleTypeName}} instance, Action<ValidationStrategy> configureStrategy)
                    => ValidationOptionsExtensions.Validate(this, instance, configureStrategy);

                /// <inheritdoc/>
                public ValueTask<ValidationResult> ValidateAsync({{simpleTypeName}} instance, CancellationToken cancellationToken = default)
                    => RunAsync(instance, (IEnumerable<string>?)null, cancellationToken);

                /// <inheritdoc/>
                public ValueTask<ValidationResult> ValidateAsync({{simpleTypeName}} instance, IEnumerable<string>? ruleSets, CancellationToken cancellationToken = default)
                    => RunAsync(instance, ruleSets, cancellationToken);

                /// <inheritdoc/>
                public ValueTask<ValidationResult> ValidateAsync({{simpleTypeName}} instance, ValidationCallOptions options, CancellationToken cancellationToken = default)
                    => RunAsync(instance, options, cancellationToken);

                /// <inheritdoc/>
                public ValueTask<ValidationResult> ValidateAsync({{simpleTypeName}} instance, Action<ValidationStrategy> configureStrategy, CancellationToken cancellationToken = default)
                    => ValidationOptionsExtensions.ValidateAsync(this, instance, configureStrategy, cancellationToken);

                /// <inheritdoc/>
                public ValidationResult Validate({{simpleTypeName}} instance, ValidationContext<{{simpleTypeName}}> context)
                    => Run(instance, context);

                /// <inheritdoc/>
                public ValueTask<ValidationResult> ValidateAsync({{simpleTypeName}} instance, ValidationContext<{{simpleTypeName}}> context, CancellationToken cancellationToken = default)
                    => RunAsync(instance, context, cancellationToken);

                /// <summary>
                /// Validates the instance and throws <see cref="ValidationException"/> when validation fails.
                /// </summary>
                public void ValidateAndThrow({{simpleTypeName}} instance) {
                    var result = Validate(instance);

                    if(!result.IsValid) {
                        throw new ValidationException(result.Errors);
                    }
                }

                /// <summary>
                /// Validates the instance with the specified rule sets and throws when validation fails.
                /// </summary>
                public void ValidateAndThrow({{simpleTypeName}} instance, IEnumerable<string>? ruleSets) {
                    var result = Validate(instance, ruleSets);

