                        var merged = new ValidationErrorCollector();
                        merged.AddRange(preErrors);
                        merged.AddRange(result.Errors);
                        result = ValidationResult.FromErrors(merged);
                    }

                    if(!result.IsValid) {
                        _onFailure?.Invoke(result);
                    }

