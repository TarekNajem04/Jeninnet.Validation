namespace Jeninnet.Validation.Generators.Emitter;

/// <summary>
/// Orchestrates the emission of C# source code for a generated validator class.
/// </summary>
internal static class ValidatorEmitter {
    internal const string CLASS_SUFFIX = "Validator";
    internal const string NAMESPACE_SUFFIX = "Validators";
    internal const string GENERATOR_VERSION = "1.0.0";
    internal const string GENERATOR_FULL_NAME = "Jeninnet.Validation.Analyzers";

    private sealed record ValidatorNames(
        string TypeNamespace,
        string SimpleTypeName,
        string ValidatorNamespace,
        string ClassName) {
        public static ValidatorNames FromDescriptor(ValidatorDescriptor descriptor) {
            var typeName = descriptor.TargetTypeName.Replace(NamingUtilities.GLOBAL_PREFIX, "");
            var typeNamespace = NamingUtilities.GetNamespace(typeName);
            var simpleTypeName = NamingUtilities.SimplifyTypeName(typeName, typeNamespace);
            var validatorNamespace = string.IsNullOrEmpty(descriptor.TargetNamespace)
                ? $"{typeNamespace}.{NAMESPACE_SUFFIX}"
                : descriptor.TargetNamespace!;
            var className = NamingUtilities.GetValidatorClassName(typeName);

            return new ValidatorNames(typeNamespace, simpleTypeName, validatorNamespace, className);
        }
    }

    /// <summary>
    /// Emits a complete validator class for the supplied
    /// <see cref="ValidatorDescriptor"/>.
    /// </summary>
    /// <param name="descriptor">The validator descriptor.</param>
    public static string Emit(ValidatorDescriptor descriptor) {
        var names = ValidatorNames.FromDescriptor(descriptor);

        // Collect all nested / foreach rules so we can generate constructor parameters.
        var injected = InjectedValidatorCollector.Collect(descriptor);

        var allRules = descriptor.Properties.SelectMany(static p => p.Rules)
                                   .Concat(descriptor.ModelRules ?? [])
                                   .ToList();
        var isAsyncOnly = allRules.Count > 0 && allRules.All(static r => r.Options.IsAsyncRule);

        var sb = new StringBuilder();
        EmitHeader(sb, names, injected, isAsyncOnly, descriptor);
        EmitRuleLists(sb, allRules, names.SimpleTypeName, names.TypeNamespace, injected);
        EmitCompositeAndCustom(sb, names.SimpleTypeName, names.ClassName, descriptor, names.TypeNamespace);
        EmitDescriptor(sb, names.ClassName, names.SimpleTypeName);
        EmitValidateMethods(sb, names.SimpleTypeName, descriptor);
        EmitFooter(sb);

        return sb.ToString();
    }

    private static void EmitHeader(
        StringBuilder sb,
        ValidatorNames names,
        List<InjectedValidator> injected,
        bool isAsyncOnly,
        ValidatorDescriptor descriptor) {

        var hookFields = EmitHookFields(names.SimpleTypeName, descriptor);
        var ctorParams = injected.Count is 0
            ? string.Empty
            : string.Join(",\n        ",
                injected.Select(v => $"{v.InterfaceType} {NamingUtilities.ToParamName(v.FieldName)}"));

        var ctorAssignments = injected.Count is 0
            ? string.Empty
            : string.Join("\n",
                injected.Select(v =>
                    $"        {v.FieldName} = {NamingUtilities.ToParamName(v.FieldName)} " +
                    $"?? throw new ArgumentNullException(nameof({NamingUtilities.ToParamName(v.FieldName)}));"));

        var fieldDeclarations = injected.Count is 0
            ? string.Empty
            : string.Join("\n",
                injected.Select(v =>
                    $"    private readonly {v.InterfaceType} {v.FieldName};"));

        sb.AppendLine(
            $$"""
            // <auto-generated/>
            // This file was generated by {{GENERATOR_FULL_NAME}} v{{GENERATOR_VERSION}}.
            // Do not edit this file manually — changes will be overwritten on next build.
            #nullable enable

            using System;
            using System.Collections.Generic;
            using System.Threading;
            using System.Threading.Tasks;

            using {{names.TypeNamespace}};

            using Jeninnet.Validation;
            using Jeninnet.Validation.Abstractions;
            using Jeninnet.Validation.Core;
            using Jeninnet.Validation.Extensions;
            using Jeninnet.Validation.Fluent;
            using Jeninnet.Validation.Metadata;
            using Jeninnet.Validation.Rules;
            using Jeninnet.Validation.Sanitization;

            namespace {{names.ValidatorNamespace}};

            /// <summary>
            /// Auto-generated validator for <see cref="{{names.SimpleTypeName}}"/>.
            /// </summary>
            [System.CodeDom.Compiler.GeneratedCode("{{GENERATOR_FULL_NAME}}", "{{GENERATOR_VERSION}}")]
            """);

        if(isAsyncOnly) {
            sb.AppendLine("[AsyncOnlyValidator]");
        }

        sb.AppendLine(
            $$"""
            public sealed partial class {{names.ClassName}} : IValidator<{{names.SimpleTypeName}}>, IValidationOptionsValidator<{{names.SimpleTypeName}}>, IValidationContextValidator<{{names.SimpleTypeName}}>, IGeneratedValidator, IValidationDescriptorProvider
            {
            {{fieldDeclarations}}
            {{hookFields}}
                private readonly List<ISyncValidationRule<{{names.SimpleTypeName}}>> _syncRules;
                private readonly List<IAsyncValidationRule<{{names.SimpleTypeName}}>> _asyncRules;
                private readonly List<ISanitizationStep<{{names.SimpleTypeName}}>> _sanitizers;
                private readonly CompositeValidator<{{names.SimpleTypeName}}> _composite;
                private readonly Lazy<ValidationDescriptor> _descriptor;

                /// <summary>
                /// Initialises the validator.  All nested and collection validators are
                /// resolved through the constructor so that DI scoped lifetimes are honoured.
                /// </summary>
            """);

        if(injected.Count is 0) {
            sb.AppendLine($"    public {names.ClassName}()");
        } else {
            sb.AppendLine($"    public {names.ClassName}({ctorParams})");
        }

        sb.AppendLine("    {");

        if(!string.IsNullOrEmpty(ctorAssignments)) {
            sb.AppendLine(ctorAssignments);
        }
    }

    private static string EmitHookFields(string simpleTypeName, ValidatorDescriptor descriptor) {
        if(descriptor.PreValidateExpression is null && descriptor.OnFailureExpression is null) {
            return string.Empty;
        }

        var sb = new StringBuilder();

        if(descriptor.PreValidateExpression is not null) {
            var errorCollector = descriptor.PreValidateHasErrors ? ", ValidationErrorCollector" : string.Empty;
            sb.AppendLine(
                $"    private static readonly Func<{simpleTypeName}, ValidationContext<{simpleTypeName}>{errorCollector}, bool>? " +
                $"_preValidate = {descriptor.PreValidateExpression};");
        }

        var onFailure = descriptor.OnFailureExpression ?? "null";
        sb.AppendLine(
            $"    private static readonly Action<ValidationResult>? _onFailure = {onFailure};");

        return sb.ToString().TrimEnd();
    }

    private static void EmitRuleLists(
        StringBuilder sb,
        List<ValidationRuleDescriptor> allRules,
        string simpleTypeName,
        string typeNamespace,
        List<InjectedValidator> injected) {

        var syncRules = allRules.Where(static r => !r.Options.IsAsyncRule).ToList();
        var asyncRules = allRules.Where(static r => r.Options.IsAsyncRule).ToList();

        // Sync rules
        if(syncRules.Count > 0) {
            sb.AppendLine("        _syncRules = new()")
              .AppendLine("        {");
            foreach(var rule in syncRules) {
                sb.AppendLine($"            {RuleExpressionEmitter.EmitRule(rule, simpleTypeName, typeNamespace, injected)},");
            }

            sb.AppendLine("        };");
        } else {
            sb.AppendLine("        _syncRules = new();");
        }

        // Async rules
        if(asyncRules.Count > 0) {
            sb.AppendLine("        _asyncRules = new()")
                .AppendLine("        {");
            foreach(var rule in asyncRules) {
                sb.AppendLine($"            {RuleExpressionEmitter.EmitRule(rule, simpleTypeName, typeNamespace, injected)},");
            }

            sb.AppendLine("        };");
        } else {
            sb.AppendLine("        _asyncRules = new();");
        }
    }

    private static void EmitCompositeAndCustom(
        StringBuilder sb,
        string simpleTypeName,
        string className,
        ValidatorDescriptor descriptor,
        string typeNamespace) => sb.AppendLine(EmitSanitizers(descriptor, simpleTypeName, typeNamespace))
            .AppendLine(
            $$"""
                    AddCustomValidators();
                    _composite = new CompositeValidator<{{simpleTypeName}}>(_syncRules, _asyncRules, typeof({{className}}).FullName, _sanitizers);
                    _descriptor = new Lazy<ValidationDescriptor>(BuildDescriptor);
                }

                /// <summary>
                /// Override in a partial class to add rules that cannot be expressed
                /// through attributes.
                /// </summary>
                partial void AddCustomValidators();
            """);

    private static string EmitSanitizers(
        ValidatorDescriptor descriptor,
        string simpleTypeName,
        string typeNamespace) {
        var sb = new StringBuilder();
        sb.AppendLine("        _sanitizers = new()")
            .AppendLine("        {");

        foreach(var step in descriptor.Sanitizers ?? []) {
            sb.AppendLine($"            {EmitSanitizer(step, simpleTypeName, typeNamespace)},");
        }

        sb.Append("        };");
        return sb.ToString();
    }

    private static string EmitSanitizer(
        SanitizeStepModel step,
        string simpleTypeName,
        string typeNamespace) {
        var simplePropertyType = NamingUtilities.SimplifyTypeName(step.PropertyTypeName, typeNamespace);
        var transforms = new List<string>();

        if(step.Trim) {
            transforms.Add("Sanitize.Trim");
        }

        if(step.NormalizeWhitespace) {
            transforms.Add("Sanitize.NormalizeWhitespace");
        }

        if(step.RemoveControlChars) {
            transforms.Add("Sanitize.RemoveControlChars");
        }

        if(step.ToUpper) {
            transforms.Add(step.Culture is null
                ? "Sanitize.ToUpperInvariant"
                : $"Sanitize.ToUpper(System.Globalization.CultureInfo.GetCultureInfo(\"{step.Culture}\"))");
        } else if(step.ToLower) {
            transforms.Add(step.Culture is null
                ? "Sanitize.ToLowerInvariant"
                : $"Sanitize.ToLower(System.Globalization.CultureInfo.GetCultureInfo(\"{step.Culture}\"))");
        }

        if(step.IsStringList) {
            for(var i = 0; i < transforms.Count; i++) {
                transforms[i] = $"Sanitize.EachElement({transforms[i]})";
            }
        }

        return $"Sanitizers.Member<{simpleTypeName}, {simplePropertyType}>(static x => x.{step.PropertyName}, \"{step.PropertyName}\", static (m, v) => m.{step.PropertyName} = v!, {string.Join(", ", transforms)})";
    }

    private static void EmitDescriptor(StringBuilder sb, string className, string simpleTypeName) => sb.AppendLine(
            $$"""
                private ValidationDescriptor BuildDescriptor() {
                    var builder = new ValidationDescriptorBuilder(
                        typeof({{className}}).FullName!,
                        typeof({{simpleTypeName}}));

                    foreach(var rule in _syncRules) {
                        builder.AddRule(rule);
                    }

                    foreach(var rule in _asyncRules) {
                        builder.AddRule(rule);
                    }

                    ConfigureDescriptor(builder);
                    return builder.Build();
                }

                /// <summary>
                /// Override in a partial class to add descriptor metadata for rules that cannot
                /// describe themselves, especially rules added by <see cref="AddCustomValidators"/>.
                /// </summary>
                partial void ConfigureDescriptor(ValidationDescriptorBuilder builder);

                /// <inheritdoc/>
                public IValidationDescriptor Describe() => _descriptor.Value;
                """);

    internal static string? GetDescriptorMessageKey(RuleKind kind) =>
        kind switch {
            RuleKind.Nested or RuleKind.ForEach or RuleKind.Custom => null,
            RuleKind.StringNotEmpty => "NotEmpty",
            RuleKind.Length or RuleKind.MaximumLength or RuleKind.MinimumLength => "Length",
            RuleKind.ScalePrecision => "PrecisionScale",
            RuleKind.PropertyEqual => "Equal",
            RuleKind.PropertyNotEqual => "NotEqual",
            RuleKind.PropertyGreaterThan => "GreaterThan",
            RuleKind.PropertyGreaterThanOrEqual => "GreaterThanOrEqual",
            RuleKind.PropertyLessThan => "LessThan",
            RuleKind.PropertyLessThanOrEqual => "LessThanOrEqual",
            _ => kind.ToString()
        };

    internal static string GetDescriptorParameterName(RuleKind kind, int index) {
        if(IsMinMaxParameter(kind)) {
            return index is 0 ? "Min" : "Max";
        }

        if(IsPropertyComparisonParameter(kind)) {
            return "Other";
        }

        return GetNamedParameterName(kind, index);
    }

    private static bool IsMinMaxParameter(RuleKind kind) =>
        kind is RuleKind.Length or RuleKind.MaximumLength or RuleKind.MinimumLength or
            RuleKind.InclusiveBetween or RuleKind.ExclusiveBetween or RuleKind.Range or
            RuleKind.Count;

    private static bool IsPropertyComparisonParameter(RuleKind kind) =>
        kind is RuleKind.PropertyEqual or RuleKind.PropertyNotEqual or
            RuleKind.PropertyGreaterThan or RuleKind.PropertyGreaterThanOrEqual or
            RuleKind.PropertyLessThan or RuleKind.PropertyLessThanOrEqual;

    private static string GetNamedParameterName(RuleKind kind, int index) =>
        kind switch {
            RuleKind.MinCount => "Min",
            RuleKind.MaxCount => "Max",
            RuleKind.ExactLength => "Length",
            RuleKind.Regex => "Pattern",
            RuleKind.In or RuleKind.NotIn => "Values",
            RuleKind.FileExtensions => "Extensions",
            RuleKind.MultipleOf => "Divisor",
            _ => GetSpecialParameterName(kind, index)
        };

    private static string GetSpecialParameterName(RuleKind kind, int index) =>
        kind switch {
            RuleKind.GreaterThan or RuleKind.GreaterThanOrEqual or RuleKind.LessThan or
            RuleKind.LessThanOrEqual or RuleKind.Equal or RuleKind.NotEqual or
            RuleKind.After or RuleKind.Before => "Threshold",
            RuleKind.Contains or RuleKind.StartsWith or RuleKind.EndsWith => "Value",
            RuleKind.Iban or RuleKind.VatNumber or RuleKind.PostalCode or RuleKind.NationalId => "Country",
            RuleKind.PasswordStrength => index is 0 ? "Policy" : "MinLength",
            RuleKind.ScalePrecision => GetScalePrecisionParameterName(index),
            _ => index.ToString(CultureInfo.InvariantCulture)
        };

    private static string GetScalePrecisionParameterName(int index) =>
        index switch {
            0 => "Precision",
            1 => "Scale",
            _ => "IgnoreTrailingZeros"
        };

    private static void EmitValidateMethods(
        StringBuilder sb,
        string simpleTypeName,
        ValidatorDescriptor descriptor) {
        if(descriptor.PreValidateExpression is null && descriptor.OnFailureExpression is null) {
            EmitDefaultValidateMethods(sb, simpleTypeName);
            return;
        }

        EmitHookValidateMethods(sb, simpleTypeName, descriptor);
    }

