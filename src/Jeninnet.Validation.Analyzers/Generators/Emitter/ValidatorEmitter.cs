                private ValidationResult Run({{simpleTypeName}} instance, IEnumerable<string>? ruleSets) {
            {{contextDeclaration}}
                    var preErrors = new ValidationErrorCollector();

            {{preValidateGuard}}

                    return Finish(preErrors, _composite.Validate(instance, ruleSets));
                }

                private ValidationResult Run({{simpleTypeName}} instance, ValidationCallOptions options) {
            {{optionsContextDeclaration}}
                    var preErrors = new ValidationErrorCollector();

            {{preValidateGuard}}

                    var result = Finish(preErrors, _composite.Validate(instance, options));

                    if(options.ThrowOnFailures && !result.IsValid) {
                        throw new ValidationException(result.Errors);
                    }

                    return result;
