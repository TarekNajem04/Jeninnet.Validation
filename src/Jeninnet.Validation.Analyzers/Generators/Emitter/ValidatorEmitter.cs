                private async ValueTask<ValidationResult> RunAsync(
                    {{simpleTypeName}} instance,
                    IEnumerable<string>? ruleSets,
                    CancellationToken cancellationToken) {
            {{contextDeclaration}}
                    var preErrors = new ValidationErrorCollector();

            {{preValidateGuard}}

