namespace Jeninnet.Validation.Generators.Emitter;

/// <summary>
/// Emits an assembly-local, reflection-free registration entry point for generated validators.
/// </summary>
internal static class GeneratedValidatorRegistryEmitter {
    /// <summary>
    /// Emits the registry for the supplied validators.
    /// </summary>
    /// <param name="descriptors">The generated validator descriptors.</param>
    /// <param name="assemblyName">The compilation assembly name.</param>
    /// <returns>The complete generated source.</returns>
    public static string Emit(IReadOnlyList<ValidatorDescriptor> descriptors, string assemblyName) {
        var entries = new List<RegistryEntry>(descriptors.Count);
        var seen = new HashSet<string>(StringComparer.Ordinal);

        for(var i = 0; i < descriptors.Count; i++) {
            var descriptor = descriptors[i];

            if(!seen.Add(descriptor.TargetTypeName)) {
                continue;
            }

            entries.Add(new RegistryEntry(
                descriptor.TargetTypeName,
                GetValidatorTypeName(descriptor)));
        }

        entries.Sort(static (left, right) =>
            StringComparer.Ordinal.Compare(left.ModelType, right.ModelType));

        var registryNamespace = GetRegistryNamespace(assemblyName);
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>")
            .AppendLine("// This file was generated by " + ValidatorEmitter.GENERATOR_FULL_NAME +
                      " v" + ValidatorEmitter.GENERATOR_VERSION + ".")
            .AppendLine("// Do not edit this file manually — changes will be overwritten on next build.")
            .AppendLine("#nullable enable")
            .AppendLine()
            .AppendLine("using System;")
            .AppendLine("using System.Diagnostics.CodeAnalysis;")
            .AppendLine("using Microsoft.Extensions.DependencyInjection;")
            .AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;")
            .AppendLine("using Jeninnet.Validation.Abstractions;")
            .AppendLine("using Jeninnet.Validation.Extensions;")
            .AppendLine()
            .AppendLine("namespace " + registryNamespace + ";")
            .AppendLine()
            .AppendLine("/// <summary>")
            .AppendLine("/// Reflection-free registration entry point for validators generated in this assembly.")
            .AppendLine("/// </summary>")
            .AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"" + ValidatorEmitter.GENERATOR_FULL_NAME +
                      "\", \"" + ValidatorEmitter.GENERATOR_VERSION + "\")]")
            .AppendLine("internal static class GeneratedValidatorRegistry")
            .AppendLine("{")
            .AppendLine("    [System.Runtime.CompilerServices.ModuleInitializer]")
            .AppendLine("    internal static void Initialize() {")
            .AppendLine("        // Register typeof pairs with the central catalog so AddValidation() needs no scanning.");

        foreach(var entry in entries) {
            sb.AppendLine("        GeneratedValidatorCatalog.Register(")
                .AppendLine("            typeof(" + entry.ModelType + "),")
                .AppendLine("            typeof(" + entry.ValidatorType + "),")
                .AppendLine("            static (services, lifetime) => RegisterValidator<" + entry.ModelType + ", " +
                          entry.ValidatorType + ">(services, lifetime));");
        }

        sb.AppendLine("    }")
            .AppendLine()
            .AppendLine("    /// <summary>")
            .AppendLine("    /// Registers every generated validator in this assembly as its concrete type and as")
            .AppendLine("    /// <c>IValidator&lt;T&gt;</c>, <c>ISyncValidator&lt;T&gt;</c>, and <c>IAsyncValidator&lt;T&gt;</c>.")
            .AppendLine("    /// </summary>")
            .AppendLine("    /// <param name=\"services\">The service collection.</param>")
            .AppendLine("    /// <param name=\"lifetime\">The lifetime used for new registrations.</param>")
            .AppendLine("    /// <returns>The service collection for chaining.</returns>")
            .AppendLine("    public static IServiceCollection Register(")
            .AppendLine("        IServiceCollection services,")
            .AppendLine("        ServiceLifetime lifetime = ServiceLifetime.Scoped) {")
            .AppendLine("        ArgumentNullException.ThrowIfNull(services);")
            .AppendLine()
            .AppendLine("        services.AddValidationCore();")
            .AppendLine();

        foreach(var entry in entries) {
            sb.AppendLine(
                "        RegisterValidator<" + entry.ModelType + ", " + entry.ValidatorType +
                ">(services, lifetime);");
        }

        sb.AppendLine()
            .AppendLine("        return services;")
            .AppendLine("    }")
            .AppendLine()
            .AppendLine("    private static void RegisterValidator<TModel, [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicConstructors)] TValidator>(")
            .AppendLine("        IServiceCollection services,")
            .AppendLine("        ServiceLifetime lifetime)")
            .AppendLine("        where TValidator : class, IValidator<TModel>, IGeneratedValidator {")
            .AppendLine("        switch(lifetime) {")
            .AppendLine("            case ServiceLifetime.Singleton:")
            .AppendLine("                services.TryAddSingleton<TValidator>();")
            .AppendLine("                services.TryAddSingleton<IValidator<TModel>, TValidator>();")
            .AppendLine("                services.TryAddSingleton<ISyncValidator<TModel>, TValidator>();")
            .AppendLine("                services.TryAddSingleton<IAsyncValidator<TModel>, TValidator>();")
            .AppendLine("                break;")
            .AppendLine("            case ServiceLifetime.Transient:")
            .AppendLine("                services.TryAddTransient<TValidator>();")
            .AppendLine("                services.TryAddTransient<IValidator<TModel>, TValidator>();")
            .AppendLine("                services.TryAddTransient<ISyncValidator<TModel>, TValidator>();")
            .AppendLine("                services.TryAddTransient<IAsyncValidator<TModel>, TValidator>();")
            .AppendLine("                break;")
            .AppendLine("            default:")
            .AppendLine("                services.TryAddScoped<TValidator>();")
            .AppendLine("                services.TryAddScoped<IValidator<TModel>, TValidator>();")
            .AppendLine("                services.TryAddScoped<ISyncValidator<TModel>, TValidator>();")
            .AppendLine("                services.TryAddScoped<IAsyncValidator<TModel>, TValidator>();")
            .AppendLine("                break;")
            .AppendLine("        }")
            .AppendLine("    }")
            .AppendLine("}")
            .AppendLine()
            .AppendLine("/// <summary>")
            .AppendLine("/// Registration helpers for validators generated in this assembly.")
            .AppendLine("/// </summary>")
            .AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"" + ValidatorEmitter.GENERATOR_FULL_NAME +
                      "\", \"" + ValidatorEmitter.GENERATOR_VERSION + "\")]")
            .AppendLine("public static class GeneratedValidatorServiceCollectionExtensions")
            .AppendLine("{")
            .AppendLine("    /// <summary>")
            .AppendLine("    /// Registers every validator generated in this assembly without assembly scanning")
            .AppendLine("    /// or reflection. Safe for trimmed and Native AOT applications.")
            .AppendLine("    /// </summary>")
            .AppendLine("    /// <param name=\"services\">The service collection.</param>")
            .AppendLine("    /// <param name=\"lifetime\">The lifetime used for new registrations.</param>")
            .AppendLine("    /// <returns>The service collection for chaining.</returns>")
            .AppendLine("    public static IServiceCollection AddGeneratedValidatorsFromThisAssembly(")
            .AppendLine("        this IServiceCollection services,")
            .AppendLine("        ServiceLifetime lifetime = ServiceLifetime.Scoped) =>")
            .AppendLine("        GeneratedValidatorRegistry.Register(services, lifetime);")
            .AppendLine("}");

        return sb.ToString();
    }

    private static string GetValidatorTypeName(ValidatorDescriptor descriptor) {
        var typeName = descriptor.TargetTypeName.Replace(NamingUtilities.GLOBAL_PREFIX, string.Empty);
        var typeNamespace = NamingUtilities.GetNamespace(typeName);
        var validatorNamespace = string.IsNullOrEmpty(descriptor.TargetNamespace)
            ? typeNamespace + "." + ValidatorEmitter.NAMESPACE_SUFFIX
            : descriptor.TargetNamespace!;
        var validatorClassName = NamingUtilities.GetValidatorClassName(typeName);

        return string.IsNullOrEmpty(validatorNamespace)
            ? "global::" + validatorClassName
            : "global::" + validatorNamespace + "." + validatorClassName;
    }

    private static string GetRegistryNamespace(string assemblyName) {
        var fallback = string.IsNullOrWhiteSpace(assemblyName) ? "Generated" : assemblyName;
        var segments = fallback.Split(['.'], StringSplitOptions.RemoveEmptyEntries);
        var builder = new StringBuilder();

        foreach(var segment in segments) {
            var safe = new StringBuilder(segment.Length);

            for(var i = 0; i < segment.Length; i++) {
                var character = segment[i];
                safe.Append(char.IsLetterOrDigit(character) || character is '_' ? character : '_');
            }

            if(safe.Length is 0) {
                continue;
            }

            if(char.IsDigit(safe[0])) {
                safe.Insert(0, '_');
            }

            if(builder.Length > 0) {
                builder.Append('.');
            }

            builder.Append(safe);
        }

        if(builder.Length is 0) {
            builder.Append("Generated");
        }

        builder.Append(".GeneratedValidation");
        return builder.ToString();
    }

    private readonly record struct RegistryEntry(string ModelType, string ValidatorType);
}
