#requires -Version 7
<#
.SYNOPSIS
    Generates the C# and JavaScript supported-rule sets from client/rules-manifest.json.

.DESCRIPTION
    The manifest is the single source of truth. This script writes:
      src/Jeninnet.Validation.ClientRules/ClientRuleSupport.g.cs
      client/src/client-rule-support.generated.js

    Use -Check to verify that both generated files match the manifest without writing.

.PARAMETER Check
    Verifies the generated files and exits 1 on drift.

.EXAMPLE
    pwsh scripts/client/generate-client-rule-support.ps1

.EXAMPLE
    pwsh scripts/client/generate-client-rule-support.ps1 -Check
#>

[CmdletBinding()]
param(
    [switch]$Check,
    [string]$RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repositoryRoot = (Resolve-Path -LiteralPath $RepositoryRoot).Path
$manifestPath = Join-Path $repositoryRoot 'client/rules-manifest.json'
$csharpPath = Join-Path $repositoryRoot 'src/Jeninnet.Validation.ClientRules/ClientRuleSupport.g.cs'
$javascriptPath = Join-Path $repositoryRoot 'client/src/client-rule-support.generated.js'

function Get-NormalizedText {
    param([Parameter(Mandatory)][string]$Text)

    return (($Text -replace "`r`n", "`n") -replace "`r", "`n").TrimEnd("`n")
}

if (-not (Test-Path -LiteralPath $manifestPath)) {
    throw "Manifest not found: $manifestPath"
}

$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
$rules = @($manifest.supportedRules | ForEach-Object { [string]$_ })

if ($manifest.schemaVersion -ne 1) {
    throw "Unsupported manifest schemaVersion: $($manifest.schemaVersion)"
}

if ($rules.Count -eq 0) {
    throw 'The manifest must declare at least one supported rule.'
}

$duplicates = @($rules | Group-Object | Where-Object Count -gt 1 | ForEach-Object Name)
if ($duplicates.Count -gt 0) {
    throw "Duplicate supported rules: $($duplicates -join ', ')"
}

foreach ($rule in $rules) {
    if ([string]::IsNullOrWhiteSpace($rule)) {
        throw 'Supported rule names must not be empty.'
    }
}

$serverOnlyRules = @(
    foreach ($group in $manifest.serverOnlyGroups) {
        foreach ($rule in @($group.rules)) {
            [string]$rule
        }
    }
)

$overlap = @($rules | Where-Object { $_ -in $serverOnlyRules })
if ($overlap.Count -gt 0) {
    throw "Rules cannot be both supported and server-only: $($overlap -join ', ')"
}

$newLine = "`n"
$csharpRules = ($rules | ForEach-Object { "        `"$_`"," }) -join $newLine
$javascriptRules = ($rules | ForEach-Object { "    `"$_`"," }) -join $newLine

$csharp = @"
//
// Copyright (c) Jeninnet.
// Part of the Jeninnet Platform.
// Repository: https://github.com/TarekNajem04/Jeninnet.Validation
// Licensed under the MIT License.
//
// <auto-generated />
// Generated from client/rules-manifest.json by scripts/client/generate-client-rule-support.ps1.
namespace Jeninnet.Validation.ClientRules;

internal static partial class ClientRuleSupport {
    internal static IReadOnlyCollection<string> SupportedRules => _supportedRules;

    private static readonly HashSet<string> _supportedRules = [
        with(StringComparer.Ordinal),
$csharpRules
    ];
}
"@

$javascript = @"
//
// Copyright (c) Jeninnet.
// Part of the Jeninnet Platform.
// Repository: https://github.com/TarekNajem04/Jeninnet.Validation
// Licensed under the MIT License.
//
// <auto-generated />
// Generated from client/rules-manifest.json by scripts/client/generate-client-rule-support.ps1.
export const supportedRules = new Set([
$javascriptRules
]);
"@

$csharp = (Get-NormalizedText $csharp) + "`n"
$javascript = (Get-NormalizedText $javascript) + "`n"

if ($Check) {
    $problems = [System.Collections.Generic.List[string]]::new()

    foreach ($pair in @(
        @{ Path = $csharpPath; Expected = $csharp; Label = 'C# support' },
        @{ Path = $javascriptPath; Expected = $javascript; Label = 'JS support' }
    )) {
        if (-not (Test-Path -LiteralPath $pair.Path)) {
            [void]$problems.Add("$($pair.Label) file is missing: $($pair.Path)")
            continue
        }

        $actual = Get-Content -LiteralPath $pair.Path -Raw

        if ((Get-NormalizedText $actual) -ne (Get-NormalizedText $pair.Expected)) {
            [void]$problems.Add("$($pair.Label) is out of date: $($pair.Path)")
        }
    }

    if ($problems.Count -gt 0) {
        $problems | ForEach-Object { Write-Host $_ -ForegroundColor Red }
        Write-Host 'Run scripts/client/generate-client-rule-support.ps1 to update the generated files.' -ForegroundColor Yellow
        exit 1
    }

    Write-Host "Client rule support is in sync: $($rules.Count) supported rules from the manifest." -ForegroundColor Green
    exit 0
}

[System.IO.File]::WriteAllText($csharpPath, $csharp, [System.Text.UTF8Encoding]::new($false))
[System.IO.File]::WriteAllText($javascriptPath, $javascript, [System.Text.UTF8Encoding]::new($false))

Write-Host "Generated client rule support for $($rules.Count) rules." -ForegroundColor Green
Write-Host "C#: $csharpPath"
Write-Host "JS: $javascriptPath"
